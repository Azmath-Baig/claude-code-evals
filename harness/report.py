#!/usr/bin/env python3
"""Turn one or more graded runs into a Markdown report.

Usage:
    python harness/report.py --run latest
    python harness/report.py --run 20260904T...-claude-code 20260904T...-aider
    python harness/report.py --run latest --out docs/_generated-results.md

With multiple runs it prints a side-by-side pass matrix by task, plus per-type
pass rates -- the table you paste into docs/03-competitive-analysis.md.
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

try:  # keep Windows consoles (cp1252) from choking on the table
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "results"


def resolve(name):
    if name == "latest":
        p = RESULTS_DIR / "latest.txt"
        if not p.exists():
            sys.exit("no latest run recorded")
        name = p.read_text(encoding="utf-8").strip()
    d = RESULTS_DIR / name
    if not (d / "grades.json").exists():
        sys.exit(f"run {name} not graded yet (run grader.py)")
    return json.loads((d / "grades.json").read_text(encoding="utf-8"))


def agent_of(run_name):
    return run_name.split("-", 1)[1] if "-" in run_name else run_name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", nargs="+", default=["latest"])
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    grades = [resolve(r) for r in args.run]
    agents = [agent_of(g["run"]) for g in grades]

    tasks = []
    seen = set()
    for g in grades:
        for row in g["rows"]:
            if row["task"] not in seen:
                seen.add(row["task"])
                tasks.append(row["task"])

    # task -> agent -> row
    cell = defaultdict(dict)
    ttype = {}
    for g, a in zip(grades, agents):
        for row in g["rows"]:
            cell[row["task"]][a] = row
            ttype[row["task"]] = row.get("type", "?")

    lines = []
    lines.append("# Results\n")
    lines.append("_Generated by harness/report.py_\n")

    # Summary line per agent
    lines.append("## Overall\n")
    lines.append("| Agent | Passed | Total | Pass rate |")
    lines.append("|---|---|---|---|")
    for g, a in zip(grades, agents):
        rate = f"{100 * g['passed'] / g['total']:.0f}%" if g["total"] else "-"
        lines.append(f"| {a} | {g['passed']} | {g['total']} | {rate} |")
    lines.append("")

    # Pass matrix
    lines.append("## By task\n")
    header = "| Task | Type | " + " | ".join(agents) + " |"
    lines.append(header)
    lines.append("|" + "---|" * (2 + len(agents)))
    sym = {True: "PASS", False: "FAIL", None: "-"}
    for t in tasks:
        cells = []
        for a in agents:
            row = cell[t].get(a)
            if not row:
                cells.append("-")
            else:
                s = sym[row["passed"]]
                if row.get("seconds") is not None:
                    s += f" {row['seconds']:.0f}s"
                cells.append(s)
        lines.append(f"| {t} | {ttype[t]} | " + " | ".join(cells) + " |")
    lines.append("")

    # Per-type pass rate
    lines.append("## By task type\n")
    lines.append("| Type | " + " | ".join(agents) + " |")
    lines.append("|" + "---|" * (1 + len(agents)))
    types = sorted(set(ttype.values()))
    for ty in types:
        row_tasks = [t for t in tasks if ttype[t] == ty]
        cells = []
        for a in agents:
            got = [cell[t].get(a) for t in row_tasks]
            got = [r for r in got if r and r["passed"] is not None]
            if not got:
                cells.append("-")
            else:
                p = sum(1 for r in got if r["passed"])
                cells.append(f"{p}/{len(got)}")
        lines.append(f"| {ty} | " + " | ".join(cells) + " |")
    lines.append("")

    text = "\n".join(lines)
    if args.out:
        (ROOT / args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
